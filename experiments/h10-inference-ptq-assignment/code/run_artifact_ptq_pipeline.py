#!/usr/bin/env python3
"""Run the H9/H10 artifact-backed PTQ pipeline for one quantized model."""

from __future__ import annotations

import argparse
import json
import os
import subprocess
import sys
from pathlib import Path


DEFAULT_POLICY_NAME = "llama31_8b_gptq_artifact"
DEFAULT_MODEL_NAME = "shuyuej/Meta-Llama-3.1-8B-GPTQ"
DEFAULT_ARTIFACT_MANIFEST = Path(
    "experiments/h9-transformer-inference-policy-search/artifact_policies.local.json"
)
DEFAULT_POLICY_GRID = Path(
    "experiments/h9-transformer-inference-policy-search/results/h9_policy_candidates.json"
)
DEFAULT_SMOKE_DIR = Path(
    "experiments/h9-transformer-inference-policy-search/results/artifact_smoke"
)
DEFAULT_BENCHMARK_DIR = Path(
    "experiments/h9-transformer-inference-policy-search/results/benchmarks"
)
DEFAULT_QUALITY_DIR = Path(
    "experiments/h9-transformer-inference-policy-search/results/quality"
)
DEFAULT_H9_SUMMARY = Path(
    "experiments/h9-transformer-inference-policy-search/results/h9_benchmark_summary.json"
)
DEFAULT_RUNTIME_CACHE_DIR = Path("tmp/h10_ptq_runtime_cache")


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--policy-name", default=DEFAULT_POLICY_NAME)
    parser.add_argument("--model-name", default=DEFAULT_MODEL_NAME)
    parser.add_argument(
        "--quantization",
        default="gptq",
        help="vLLM quantization value for the artifact, e.g. gptq, gptq_marlin, awq, awq_marlin.",
    )
    parser.add_argument("--dtype", default="float16")
    parser.add_argument("--hardware-label", default=os.environ.get("HARDWARE_LABEL", "rtx3090-lab"))
    parser.add_argument("--cuda-visible-devices", default=os.environ.get("CUDA_VISIBLE_DEVICES"))
    parser.add_argument("--artifact-manifest", type=Path, default=DEFAULT_ARTIFACT_MANIFEST)
    parser.add_argument("--policy-grid", type=Path, default=DEFAULT_POLICY_GRID)
    parser.add_argument("--smoke-output-dir", type=Path, default=DEFAULT_SMOKE_DIR)
    parser.add_argument("--benchmark-output-dir", type=Path, default=DEFAULT_BENCHMARK_DIR)
    parser.add_argument("--quality-output-dir", type=Path, default=DEFAULT_QUALITY_DIR)
    parser.add_argument("--h9-summary-output", type=Path, default=DEFAULT_H9_SUMMARY)
    parser.add_argument("--quality-gpu-memory-utilization", type=float, default=0.78)
    parser.add_argument("--quality-batch-size", type=int, default=1)
    parser.add_argument("--runtime-cache-dir", type=Path, default=DEFAULT_RUNTIME_CACHE_DIR)
    parser.add_argument("--smoke-only", action="store_true")
    parser.add_argument("--skip-smoke", action="store_true")
    parser.add_argument("--skip-benchmark", action="store_true")
    parser.add_argument("--skip-quality", action="store_true")
    parser.add_argument("--dry-run", action="store_true", help="Print commands without running them.")
    return parser.parse_args()


def write_manifest(args: argparse.Namespace) -> None:
    payload = {
        "artifact_policies": [
            {
                "policy_name": args.policy_name,
                "model_name": args.model_name,
                "quantization": args.quantization,
                "dtype": args.dtype,
                "expected_role": "artifact_backed_quantization_candidate",
                "description": (
                    f"Artifact-backed {args.quantization} PTQ policy for {args.model_name}."
                ),
                "notes": (
                    "Generated by run_artifact_ptq_pipeline.py. This is an inference PTQ "
                    "artifact, not a newly trained model."
                ),
            }
        ]
    }
    args.artifact_manifest.parent.mkdir(parents=True, exist_ok=True)
    args.artifact_manifest.write_text(json.dumps(payload, indent=2) + "\n", encoding="utf-8")
    print(f"wrote {args.artifact_manifest}")


def command_env(args: argparse.Namespace) -> dict[str, str]:
    env = os.environ.copy()
    if args.cuda_visible_devices is not None:
        env["CUDA_VISIBLE_DEVICES"] = str(args.cuda_visible_devices)
    env["HARDWARE_LABEL"] = args.hardware_label
    runtime_cache = args.runtime_cache_dir.expanduser().resolve()
    runtime_cache.mkdir(parents=True, exist_ok=True)
    for child in ["tmp", "torchinductor", "triton", "cuda", "xdg", "vllm"]:
        (runtime_cache / child).mkdir(parents=True, exist_ok=True)
    env["TMPDIR"] = str(runtime_cache / "tmp")
    env["TEMP"] = str(runtime_cache / "tmp")
    env["TMP"] = str(runtime_cache / "tmp")
    env["TORCHINDUCTOR_CACHE_DIR"] = str(runtime_cache / "torchinductor")
    env["TRITON_CACHE_DIR"] = str(runtime_cache / "triton")
    env["CUDA_CACHE_PATH"] = str(runtime_cache / "cuda")
    env["XDG_CACHE_HOME"] = str(runtime_cache / "xdg")
    env["VLLM_CACHE_ROOT"] = str(runtime_cache / "vllm")
    return env


def run(cmd: list[str], args: argparse.Namespace) -> None:
    printable = " ".join(cmd)
    if args.cuda_visible_devices is not None:
        printable = f"CUDA_VISIBLE_DEVICES={args.cuda_visible_devices} {printable}"
    print(f"\n$ {printable}")
    if args.dry_run:
        return
    subprocess.run(cmd, check=True, env=command_env(args))


def result_status(path: Path) -> str | None:
    if not path.exists():
        return None
    payload = json.loads(path.read_text(encoding="utf-8"))
    return payload.get("status")


def require_completed(path: Path, label: str) -> None:
    status = result_status(path)
    if status != "completed":
        raise SystemExit(f"{label} did not complete: status={status!r}, path={path}")


def main() -> None:
    args = parse_args()
    write_manifest(args)

    python = sys.executable
    run(
        [
            python,
            "experiments/h9-transformer-inference-policy-search/code/generate_h9_policies.py",
            "--artifact-policies",
            str(args.artifact_manifest),
            "--output",
            str(args.policy_grid),
        ],
        args,
    )

    smoke_result = args.smoke_output_dir / args.policy_name / "benchmark.json"
    if not args.skip_smoke:
        run(
            [
                python,
                "experiments/h9-transformer-inference-policy-search/code/run_h9_vllm_benchmark.py",
                "--policies",
                str(args.policy_grid),
                "--policy-name",
                args.policy_name,
                "--output-dir",
                str(args.smoke_output_dir),
                "--hardware-label",
                args.hardware_label,
                "--smoke",
                "--repeats",
                "1",
                "--warmup-runs",
                "0",
            ],
            args,
        )
        if not args.dry_run:
            require_completed(smoke_result, "smoke benchmark")

    if args.smoke_only:
        print("\nSmoke stage finished. Re-run without --smoke-only for benchmark, quality, and H10 solve.")
        return

    benchmark_result = args.benchmark_output_dir / args.policy_name / "benchmark.json"
    quality_result = args.quality_output_dir / args.policy_name / "quality.json"
    if not args.skip_benchmark:
        run(
            [
                python,
                "experiments/h9-transformer-inference-policy-search/code/run_h9_vllm_benchmark.py",
                "--policies",
                str(args.policy_grid),
                "--policy-name",
                args.policy_name,
                "--output-dir",
                str(args.benchmark_output_dir),
                "--hardware-label",
                args.hardware_label,
            ],
            args,
        )
        if not args.dry_run:
            require_completed(benchmark_result, "full benchmark")
    else:
        print(f"\nskipping benchmark; expecting existing artifact at {benchmark_result}")

    if not args.skip_quality:
        run(
            [
                python,
                "experiments/h9-transformer-inference-policy-search/code/run_h9_vllm_quality.py",
                "--policies",
                str(args.policy_grid),
                "--policy-name",
                args.policy_name,
                "--output-dir",
                str(args.quality_output_dir),
                "--hardware-label",
                args.hardware_label,
                "--quality-batch-size",
                str(args.quality_batch_size),
                "--gpu-memory-utilization",
                str(args.quality_gpu_memory_utilization),
            ],
            args,
        )
        if not args.dry_run:
            require_completed(quality_result, "quality run")
    else:
        print(f"\nskipping quality; expecting existing artifact at {quality_result}")

    run(
        [
            python,
            "experiments/h9-transformer-inference-policy-search/code/summarize_h9_results.py",
            "--results-dir",
            str(args.benchmark_output_dir),
            "--quality-dir",
            str(args.quality_output_dir),
            "--output",
            str(args.h9_summary_output),
        ],
        args,
    )
    run(
        [python, "experiments/h10-inference-ptq-assignment/code/build_inference_action_table.py"],
        args,
    )
    run(
        [python, "experiments/h10-inference-ptq-assignment/code/solve_inference_assignment.py"],
        args,
    )
    print("\nDone. Check experiments/h10-inference-ptq-assignment/results/selected_policy.json")


if __name__ == "__main__":
    main()
